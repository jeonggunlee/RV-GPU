`timescale 1ns/1ps
// =============================================================================
// 물리 lane 하나의 레지스터 파일: 4 warp × 32 register × 32bit = 512byte.
//
// simt_sm은 이 모듈을 lane 0..7에 하나씩, 총 8개 생성한다(전체 저장 용량 4KiB).
// 각 인스턴스는 같은 lane 번호에 배치된 4개 thread의 레지스터를 보관한다.
// 예: lane 3 인스턴스는 thread ID 3, 11, 19, 27의 x0..x31을 보관한다.
// 따라서 같은 warp에서 같은 x5를 읽어도 lane마다 서로 다른 값이 나올 수 있다.
//
// warp 전환은 읽기 주소의 상위 2비트만 바꾸는 동작이다. 레지스터 데이터를
// 다른 저장소로 복사하거나 저장/복원할 필요 없이 4개 문맥을 동시에 유지한다.
// Thread/warp/lane ID CSR은 여기 저장하지 않는다. simt_sm이 값을 생성하여
// CSR 읽기 명령의 목적 GPR에 기록할 때만 아래 쓰기 포트를 사용한다.
// =============================================================================
module simt_regfile(
    // clk: 동기 쓰기에 사용하는 클럭. 읽기 출력은 클럭을 기다리지 않는다.
    // warp: 두 읽기 포트가 공통으로 선택하는 실행 중 warp 번호(0..3).
    input wire clk, input wire [1:0] warp,
    // rs1/rs2: 현재 warp에서 읽을 RV32I 소스 register 번호(0..31).
    // 같은 번호를 지정하면 두 출력에 같은 값이 나온다.
    input wire [4:0] rs1,rs2,
    // a/b: 두 소스 register의 조합 읽기 결과. 내부 출력 레지스터는 없다.
    output wire [31:0] a,b,
    // we: 이 lane의 쓰기 허가. active mask와 fault/x0 억제는 상위 SM이 결정한다.
    // waddr: {쓰기 대상 warp[1:0], 목적 register[4:0]}인 7비트 절대 주소.
    // 읽기용 warp 입력과 독립적이므로 INIT에서도 별도 주소를 지정할 수 있다.
    // wdata: 이 lane에 기록할 32비트 값. 다른 lane은 별도의 쓰기 데이터를 가진다.
    input wire we, input wire [6:0] waddr, input wire [31:0] wdata
);
    // -------------------------------------------------------------------------
    // 1. 저장 배열과 주소 배치
    // -------------------------------------------------------------------------
    // regs의 주소 = warp_id * 32 + register_id.
    //   warp 0:   0..31  / warp 1: 32..63
    //   warp 2:  64..95  / warp 3: 96..127
    // 예: warp 2의 x5는 regs[69]이며, 다른 warp의 x5와 별도 저장 공간이다.
    //
    // distributed 속성은 FPGA LUT RAM 사용을 유도한다. 비동기 읽기 2포트와
    // 동기 쓰기 1포트를 제공하며 실제 물리 LUT 배치는 합성 도구가 결정한다.
    // 이 모듈에는 reset/initial이 없다. simt_sm의 INIT이 128클럭 동안 주소
    // 0..127을 순회하며 8개 lane을 동시에 초기화한다. 따라서 큰 배열 전체에
    // reset 회로를 붙이지 않는다. 초기화 전 일반 register 값은 사용하면 안 된다.
    (* ram_style="distributed" *) reg [31:0] regs[0:127];

    // -------------------------------------------------------------------------
    // 2. 비동기 읽기 2포트와 x0 규칙
    // -------------------------------------------------------------------------
    // {warp, rs1/rs2}는 2비트 warp와 5비트 register 번호를 이어 붙인 주소이다.
    // warp, rs1/rs2 또는 해당 저장 내용이 바뀌면 조합 전파 지연 뒤 출력도 바뀐다.
    // 읽기 enable이나 별도의 read 클럭은 없으며 두 소스를 동시에 읽는다.
    //
    // RISC-V의 x0는 항상 0이므로 배열 내용과 무관하게 출력 mux에서 0을 반환한다.
    // 배열에는 warp마다 x0 자리도 있지만 그 저장값은 소프트웨어에 보이지 않는다.
    // INIT은 그 자리까지 초기화하며, 정상 실행 중 rd=x0 쓰기는 상위 SM이 억제한다.
    assign a=(rs1==0)?32'b0:regs[{warp,rs1}];
    assign b=(rs2==0)?32'b0:regs[{warp,rs2}];

    // -------------------------------------------------------------------------
    // 3. 동기 쓰기 1포트
    // -------------------------------------------------------------------------
    // 상승 에지에서 we=1일 때만 waddr 한 곳에 wdata를 저장한다. we=0이면 유지한다.
    // 쓰기 대상 warp는 waddr 안에 들어 있으므로 읽기용 warp를 별도로 참조하지 않는다.
    // 이 모듈 자체는 active mask/fault/명령 종류를 모르고 we만 따른다.
    //
    // 같은 주소를 읽으면서 쓰면 RTL에서 에지 직전에는 기존 값이 보이고,
    // nonblocking 갱신 및 조합 전파 뒤에는 새 값이 보인다(x0는 계속 0).
    // 별도 forwarding/bypass 회로는 없다. 현재 SM은 비파이프라인 구조여서
    // 다음 명령이 피연산자를 소비하기 전에 이전 명령의 쓰기가 완료된다.
    // 향후 ALU와 LSU writeback을 동시에 처리하려면 상위에서 쓰기 포트를 중재하거나
    // 포트 구조를 바꿔야 한다. 이 인스턴스는 한 클럭에 한 주소만 쓸 수 있다.
    always @(posedge clk) if(we) regs[waddr]<=wdata;
endmodule
